function user(
  partial: Pick<SavedUser, "mid" | "uname" | "mtime"> &
    Partial<Pick<SavedUser, "face" | "sign" | "official" | "officialType" | "special" | "mutual">> & {
      inspect: Omit<InspectResult, "mid">
    }
): SavedUser {
  const inspect = { ...partial.inspect, mid: partial.mid }
  return {
    mid: partial.mid,
    uname: partial.uname,
    face: "",
    sign: partial.sign ?? "",
    official: partial.official ?? "",
    officialType: partial.officialType ?? -1,
    special: partial.special ?? false,
    mutual: partial.mutual ?? false,
    mtime: partial.mtime,
    inspect,
  }
}
